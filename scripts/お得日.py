"""その日が楽天の「お得日」かどうかを、日付だけで決める。

なぜこれを作ったか
------------------
  代表共有のnote記事（Threads×楽天アフィリ）で、2日で66,102円になった投稿は
  商品の紹介ではなく「期間限定クーポン」の紹介だった。
  成果が出た型は「誰向け ＋ どんなお得 ＋ 期限」。
  商品にも宿にも「期限」は作れないが、楽天のお得日にはもともと期限がある。

大前提
------
  **倍率や割引率の数字は、この投稿では書かない。**
  楽天のキャンペーンは予告なく変わる。数字を書くと、変わった日に嘘になる。
  「ポイントが増える日」「クーポンが出る日」までにとどめて、
  条件はリンク先で見てもらう。

  **エントリーが要るものは、要ると必ず書く。**
  エントリーを忘れると1円も得しないので、書かないと読む人に損をさせる。

裏取り（2026-09-23 に楽天の公式ページで確認）
--------------------------------------------
  - 毎月1日 ワンダフルデー … エントリー必須・3,000円以上・会員ランク条件なし
    https://event.rakuten.co.jp/campaign/point-up/wonderfulday/
  - 5と0のつく日（楽天市場）… エントリー必須（毎回）・楽天カード利用が条件
    月間の上限あり・楽天ふるさと納税は対象外
    https://event.rakuten.co.jp/card/pointday/
  - 5と0のつく日（楽天トラベル）… **エントリー不要**・国内宿泊クーポンが出る
    https://travel.rakuten.co.jp/camp/50luxday/top/
  - 毎月18日 ご愛顧感謝デー … エントリー必須・**ゴールド会員以上だけ**
    https://event.rakuten.co.jp/campaign/rank/point/
"""

from __future__ import annotations

from datetime import date

# 5と0のつく日。2月30日は無い。
_五と〇 = (5, 10, 15, 20, 25, 30)


def 市場(対象日: date) -> dict | None:
    """その日の楽天市場のお得日。無ければ None。

    同じ日に重なることがある（1日と5と0のつく日は重ならないが、
    18日と5と0のつく日も重ならない）。いまは重ならないので1つだけ返す。
    """
    d = 対象日.day
    if d == 1:
        return {
            "名": "ワンダフルデー",
            "いつ": "毎月1日",
            "何が": "全ショップのポイントが増える日",
            "条件": "エントリーが要ります。合計3,000円以上から",
            "誰でも": True,
            "期限": "今日中",
        }
    if d == 18:
        return {
            "名": "ご愛顧感謝デー",
            "いつ": "毎月18日",
            "何が": "会員ランクに応じてポイントが増える日",
            "条件": "エントリーが要ります。ゴールド会員以上が対象です",
            "誰でも": False,
            "期限": "今日中",
        }
    if d in _五と〇:
        return {
            "名": "5と0のつく日",
            "いつ": "毎月5・10・15・20・25・30日",
            "何が": "楽天カードで買うとポイントが増える日",
            "条件": "エントリーが要ります。開催日ごとに毎回。楽天カードでの支払いが条件です",
            "誰でも": True,
            "期限": "今日中",
        }
    return None


def 旅(対象日: date) -> dict | None:
    """その日の楽天トラベルのお得日。無ければ None。

    市場と違い、5と0のつく日はエントリーが要らない。
    note記事で成果が出たのもこちら（旅行クーポン）。
    """
    if 対象日.day in _五と〇:
        return {
            "名": "5と0のつく日",
            "いつ": "毎月5・10・15・20・25・30日",
            "何が": "国内宿泊に使えるクーポンが出る日",
            "条件": "エントリーは要りません。クーポンは先着なので、なくなることがあります",
            "期限": "今日中（クーポンの取得）",
        }
    return None


def 説明(お得日: dict) -> str:
    """prompt に渡す一行。"""
    かけら = [f"{お得日['名']}（{お得日['いつ']}）", お得日["何が"], お得日["条件"]]
    return " ／ ".join(かけら)
