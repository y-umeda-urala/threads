def 当てはまる(切り口: dict, 品: dict) -> bool:
    if "金額" in 切り口:
        下, 上 = 切り口["金額"]
        額 = 品.get("寄付額")
        return bool(額) and 下 <= int(額) < 上
    名 = str(品.get("名") or "")
    return any(w in 名 for w in 切り口["探す語"])


def どの切り口か(品: dict) -> dict | None:
    """その品が最初に当てはまる切り口。返信の一言に使う。"""
    for き in 切り口たち:
        if 当てはまる(き, 品):
            return き
    return None


