def _中身がある(s: str) -> bool:
    """【…】を全部取ってもまだ言葉が残るか。宣伝文句だけの行を防ぐ。"""
    return len(re.sub(r"【[^】]*】", "", s).strip(" \u3000・、/／")) >= 4


def _括弧の外の区切り(s: str) -> int:
    """【…】の外にある「／ 」「/ 」の位置。検索語の羅列がそこから始まる。

    括弧の中の「令和8年産 / 令和9年産」や、数量の「5kg/10kg」で切らないように、
    括弧の深さを数えながら探す。
    """
    深さ = 0
    for i, c in enumerate(s):
        if c in "【（(「《":
            深さ += 1
        elif c in "】）)」》":
            深さ = max(0, 深さ - 1)
        elif 深さ == 0 and c in "／/" and i > 12:
            前 = s[i - 1]
            後 = s[i + 1:i + 2]
            # 「5kg/10kg」のように前後が詰まっているものは数量なので切らない
            if 前 in " \u3000" or 後 in (" ", "\u3000"):
                return i
    return -1


def 見せる名(品: dict, 上限: int = 50) -> str:
    """楽天の商品名を、読める長さに整える。

    2026-09-25、代表の指示で「短く言い換えた名前」から「元のタイトルの頭」に変えた。
      > ふるさと納税の1投稿目に価格はいらないと思います。素直にタイトルではだめ？
    元のタイトルは中央128字あり、7件並べると入らない。なので頭だけを使う。

    落とすもの:
      - 枠の名前と重なる「【ふるさと納税】」
      - 「[A-013010]」のような商品コード
      - 「｜」「／ 」より後ろの検索語の羅列（楽天の商品名はここから先が飾り）
    切るときは【…】の切れ目を優先する。宣伝文句だけが残る切り方はしない。
    """
    s = str(品.get("生の名") or 品.get("名") or "")
    s = s.replace("【ふるさと納税】", " ")
    s = re.sub(r"\[[A-Za-z0-9\-_]{3,}\]", " ", s)
    s = re.sub(r"^\s*[《＼\\][^》]{0,40}》\s*", " ", s)
    s = re.sub(r"^[\s\u3000]*[》】\]）)／/｜|]+", " ", s)
    # 「｜」だけでなく、区切りに使われた半角の l・I もここで切る
    s = re.split(r"[｜|]|(?<=[\s\u3000])[lI](?=[\s\u3000])", s)[0]
    i = _括弧の外の区切り(s)
    if i > 0:
        s = s[:i]
    s = re.sub(r"[\u3000\s]+", " ", s).strip(" \u3000・、/／")

    if len(s) <= 上限:
        return _とじる(s)
    切 = s[:上限 + 1]
    閉 = 切.rfind("】")
    if 閉 >= 上限 // 2 and _中身がある(切[:閉 + 1]):
        return _とじる(切[:閉 + 1])
    空 = 切.rfind(" ")
    切 = 切[:空] if 空 >= 上限 // 2 else s[:上限]
    return _とじる(切)


def _とじる(s: str) -> str:
    """切った拍子に開いたままになった括弧を落とす。"""
    for 開, 閉 in (("【", "】"), ("（", "）"), ("(", ")"), ("「", "」"), ("《", "》")):
        while s.count(開) > s.count(閉):
            i = s.rfind(開)
            if i < 0:
                break
            s = (s[:i] + s[i + 1:]).strip(" 　・、")
        while s.count(閉) > s.count(開):
            i = s.rfind(閉)
            if i < 0:
                break
            s = (s[:i] + s[i + 1:]).strip(" 　・、")
    return s


def 今日のまとめ(対象日: date, 品たち: list[dict] | None = None,
              いくつ: int = 5) -> dict | None:
    """その日の切り口と返礼品を返す。当てはまりが少ない切り口は飛ばす。"""
    品たち = 読む() if 品たち is None else 品たち
    if not 品たち:
        return None
    日数 = (対象日 - 起点).days
    # 3件そろえば切り口として出す。4件だと「越前がに」のような
    # 福井ならではの切り口が立たない日が出る（2026-09-25）。
    # 切り口が立つ線は3件で固定（見せる件数に連動させない。宿と同じ理由）
    最低 = 3

    # **飛ばし方に注意。** 使えない切り口に当たった日に次の番号へ進むと、
    # その番号は翌日ぶんでもあるので、2日続けて同じ切り口になる
    # （2026-09-26、宿の枠で実際に起きた）。
    # 先に使える切り口だけを集めてから、その中で日付順に回す。
    使える = []
    for き in 切り口たち:
        合う = [p for p in sorted(品たち, key=lambda x: str(x.get("itemCode")))
                if 当てはまる(き, p)]
        if len(合う) >= 最低:
            使える.append((き, 合う))
    if not 使える:
        return None

    for _ in (0,):
        き, 合う = 使える[日数 % len(使える)]
        ずらし = 日数 % len(合う)
        並べ直し = 合う[ずらし:] + 合う[:ずらし]
        # 自治体がばらけるように、まず違う自治体から1件ずつ
        選ぶ, 見た = [], set()
        for p in 並べ直し:
            if p.get("自治体") in 見た:
                continue
            選ぶ.append(p)
            見た.add(p.get("自治体"))
            if len(選ぶ) >= いくつ:
                break
        for p in 並べ直し:
            if len(選ぶ) >= いくつ:
                break
            if p not in 選ぶ:
                選ぶ.append(p)
        return {"切り口": き, "品": 選ぶ}
    return None


def 一覧の行(まとめ: dict) -> list[str]:
    """本文に並べる一覧。リンクは入れない。

    2026-09-25、代表の指示で寄付額を落とした。
      > ふるさと納税の1投稿目に価格はいらないと思います。
    金額は着地したページで見える。1投稿目は「何が福井ならではか」に使う。
    """
    品たち = まとめ["品"]
    上限 = 名前の予算.get(len(品たち), 44)
    出 = []
    for i, p in enumerate(品たち):
        市 = str(p.get("自治体") or "福井")
        絵 = 自治体の絵文字.get(市, "📍")
        出.append(f"{丸数字[i]} {絵} {見せる名(p, 上限)}（{市}）")
    return 出


def 返信の行(まとめ: dict) -> list[str]:
    """返信に並べる、返礼品ごとの一行とリンク。1件で1つ。"""
    出 = []
    for i, p in enumerate(まとめ["品"]):
        市 = str(p.get("自治体") or "福井")
        額 = f"寄付{int(p['寄付額']):,}円" if p.get("寄付額") else ""
        件 = f"レビュー{p['レビュー数']}件" if p.get("レビュー数") else ""
        かけら = [x for x in (市, 額, 件) if x]
        出.append(f"{丸数字[i]} {見せる名(p, 40)}（{'・'.join(かけら)}）\n{p['url']}")
    return 出
